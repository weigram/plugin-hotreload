#!/usr/bin/env python3
"""Render the JDK test matrix in README.md from test/jdk-matrix.sh results."""
from __future__ import annotations

import re
import sys
from pathlib import Path

BEGIN = "<!-- BEGIN JDK-MATRIX -->"
END = "<!-- END JDK-MATRIX -->"

ROWS = [
    ("body", "方法体"),
    ("xml", "Mapper XML"),
    ("add_method_field", "增加方法/字段"),
    ("add_annotation", "增加类注解"),
    ("add_interface", "增加接口"),
    ("remove_method_field", "删除方法/字段"),
    ("remove_interface", "删除接口"),
    ("replace_interface", "替换接口"),
    ("replace_superclass", "替换父类"),
]
CASE_ROWS = {
    "add method + field": "add_method_field",
    "add class annotation": "add_annotation",
    "add interface": "add_interface",
    "remove method + field": "remove_method_field",
    "remove interface": "remove_interface",
    "replace interface": "replace_interface",
    "replace superclass": "replace_superclass",
}


def short_reason(reason: str) -> str:
    reason = reason.strip()
    if "attempted to change superclass or interfaces" in reason:
        return "层次变更不支持"
    if reason.startswith("wanted:"):
        return "结果未更新"
    if reason == "e2e failed":
        return "e2e 失败"
    if "does not accept -XX:+AllowEnhancedClassRedefinition" in reason:
        return "需要 JBR 增强重定义"
    reason = reason.replace("|", "\\|")
    return reason[:48]


def column_key(label: str):
    match = re.search(r"(\d+)", label)
    major = int(match.group(1)) if match else 999
    return (major, 0 if label.startswith("JBR") else 1)


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: render-matrix.py RESULTS.tsv README.md", file=sys.stderr)
        return 2
    results = Path(sys.argv[1])
    readme = Path(sys.argv[2])

    cells: dict[tuple[str, str], tuple[str, str]] = {}
    columns: set[str] = set()
    for raw in results.read_text().splitlines():
        parts = raw.split("\t")
        if len(parts) < 3:
            continue
        label, case, status = parts[0], parts[1], parts[2]
        reason = parts[3] if len(parts) > 3 else ""
        row = CASE_ROWS.get(case, case)
        if row not in {key for key, _ in ROWS}:
            continue
        columns.add(label)
        cells[(label, row)] = (status, reason)

    if not columns:
        print("no matrix results", file=sys.stderr)
        return 1

    columns = sorted(columns, key=column_key)
    header = "| 修改 | " + " | ".join(columns) + " |"
    separator = "| --- | " + " | ".join("---" for _ in columns) + " |"
    lines = [
        BEGIN,
        "<!-- generated by test/jdk-matrix.sh; do not edit by hand -->",
        header,
        separator,
    ]
    for key, title in ROWS:
        row = [title]
        for label in columns:
            status, reason = cells.get((label, key), ("", ""))
            if status == "PASS":
                cell = "✅"
            elif status == "FAIL":
                cell = "❌ " + short_reason(reason)
            else:
                cell = "❌ 需要 JBR 增强重定义" if not label.startswith("JBR") else "❌ 未测试"
            row.append(cell)
        lines.append("| " + " | ".join(row) + " |")
    lines.append(END)
    block = "\n".join(lines)

    text = readme.read_text()
    if BEGIN not in text or END not in text:
        print(f"{readme}: missing {BEGIN} / {END}", file=sys.stderr)
        return 1
    text = re.sub(
        re.escape(BEGIN) + r".*?" + re.escape(END),
        lambda _match: block,
        text,
        count=1,
        flags=re.S,
    )
    readme.write_text(text)
    print(f"updated {readme} with {len(columns)} JDK column(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
